"""Write cad/mass-properties.md from cad/mass-properties.json (produced by build_surang.py)."""
import json, os, re
CAD = os.path.dirname(os.path.abspath(__file__))
M = json.load(open(os.path.join(CAD, 'mass-properties.json')))
A = json.load(open(os.path.join(CAD, 'analysis.json')))
alloc = dict(M['alloc'])
L = []
L.append('# SURANG-SUTRA mass properties (CAD estimate)\n')
L.append('Generated by `cad/mass_report.py` from `cad/mass-properties.json` (written by `build_surang.py`). '
         'Everything is a design calculation: printed, moulded and composite parts are CAD volume times density; '
         'bought parts use catalogue or baseline masses. Nothing has been weighed.\n')
L.append('Densities (g/cm³): ' + ', '.join(f'{k} {v}' for k, v in M['density'].items()) +
         '. Al standoffs, steel pins/bearings, FR4 and PTFE are not in the brief, so standard values are used.\n')
L.append('## Summary by baseline allocation\n')
L.append('| Group | CAD-volume mass (g) | Catalogue / allowance (g) | Total (g) | Baseline allocation (g) | Delta (g) |')
L.append('|---|---:|---:|---:|---:|---:|')
tot_al = 0
for g, al in M['alloc']:
    v = M['groups'].get(g, dict(mass=0, cad=0, cat=0))
    tot_al += al
    L.append(f"| {g} | {v['cad']:.0f} | {v['cat']:.0f} | **{v['mass']:.0f}** | {al} | {v['mass'] - al:+.0f} |")
tot = M['total_g']
L.append(f"| Reserve | | | | 70 | |")
L.append(f"| **All-up** | | | **{tot:.0f}** | **{tot_al + 70}** (cap 2400) | **{tot - 2400:+.0f}** vs cap |")
L.append('')
L.append(f"- All-up CAD estimate **{tot / 1000:.2f} kg**: {tot_al - tot:.0f} g under the {tot_al} g of named allocations, "
         f"{tot_al + 70 - tot:.0f} g under allocations + 70 g reserve, and {2400 - tot:.0f} g under the 2.40 kg cap.")
L.append(f"- Thrust check at the ≥ 6 kgf target: T/W = 6.0 / {tot / 1000:.2f} = **{6.0 / (tot / 1000):.2f}** (target ≥ 2.5).")
L.append(f"- Over allocation: **Cage** (+{M['groups']['Cage']['mass'] - 400:.0f} g) and **Cassette + 5 pucks** "
         f"(+{M['groups']['Cassette + 5 pucks']['mass'] - 170:.0f} g). Under: ESC + props, Pi, sensors, frame, gas.")
L.append('')
L.append('## Line items\n')
L.append('| Group | Item | Source | Material | Mass (g) |')
L.append('|---|---|---|---|---:|')
for g, _ in M['alloc']:
    v = M['groups'].get(g)
    if not v:
        continue
    agg = {}
    for it in v['items']:
        n = it['name']
        key = re.sub(r'_\d+$', '', n) if n.startswith('Strut_') else n
        key = 'Strut (120 off)' if n.startswith('Strut_') else key
        key = 'Hub_M6 (30 off)' if n.startswith('Hub_M') else key
        key = 'Hub_V5 (10 off)' if n.startswith('Hub_V') else key
        key = 'TPU hub cap (40 off)' if n.startswith('Cap_') else key
        m = re.match(r'Puck\d+_(.*)', n)
        if m:
            key = f'5 pucks: {m.group(1).replace("Puck_", "")}'
        a = agg.setdefault(key, [0.0, it['src'], it['mat']])
        a[0] += it['g']
    for k, (g_, src, mat) in sorted(agg.items(), key=lambda x: -x[1][0]):
        if g_ <= 0:
            continue
        L.append(f'| {g} | {k} | {src} | {mat} | {g_:.1f} |')
L.append('')
cg, icg, ccg = M['cg_mm'], M['inner_cg_mm'], M['cage_cg_mm']
L.append('## Centre of gravity\n')
L.append('Origin = cage centre = axle centreline. X forward (nose), Y along the axle, Z up. Cage in its rest pose.\n')
L.append('| Assembly | Mass (g) | CG x (mm) | CG y (mm) | CG z (mm) |')
L.append('|---|---:|---:|---:|---:|')
L.append(f"| All-up | {tot:.0f} | {cg[0]:.1f} | {cg[1]:.1f} | {cg[2]:.1f} |")
L.append(f"| Hanging core (everything except the cage) | {M['inner_g']:.0f} | {icg[0]:.1f} | {icg[1]:.1f} | {icg[2]:.1f} |")
L.append(f"| Cage (rotates on the bearings) | {M['cage_g']:.0f} | {ccg[0]:.1f} | {ccg[1]:.1f} | {ccg[2]:.1f} |")
L.append('')
L.append(f"- The battery is placed at x = {M['batt_x_mm']:.1f} mm by the build script so the hanging core balances fore-aft (x_CG = 0), "
         "which keeps the frame level on the axle.")
L.append(f"- The hanging core CG sits **{-icg[2]:.1f} mm below the axle**: pendulum-stable but a short arm "
         f"(restoring moment ≈ {M['inner_g'] / 1000 * 9.81 * -icg[2] / 1000:.2f} N·m per radian of tilt). "
         "Lowering the battery or cassette would lengthen it.")
L.append(f"- Lateral CG y = +{icg[1]:.1f} mm (core) comes from the cassette offset to +54 mm (see README, puck exit). "
         "It falls as pucks are dropped; the FC trims it in flight, or the gas package can move further to −Y.")
I = M['inertia_kgm2_about_cg']
L.append('')
L.append('Inertia about the all-up CG (kg·m², solids at uniform density, bought blocks scaled to catalogue mass):\n')
L.append('| | x | y | z |')
L.append('|---|---:|---:|---:|')
for n, row in zip('xyz', I):
    L.append(f'| {n} | ' + ' | '.join(f'{v:.4f}' for v in row) + ' |')
L.append('')
L.append('## SUTRA puck (one)\n')
L.append('| Part | Source | Material | Mass (g) |')
L.append('|---|---|---|---:|')
for p in M['puck_parts']:
    L.append(f"| {p['name'].replace('Puck_', '')} | {p['src']} | {p['mat']} | {p['g']:.1f} |")
L.append(f"| screws + tag label (allowance) | catalogue | | 0.8 |")
L.append(f"| **Total** | | | **{M['single_puck_g']:.1f}** (target ≤ 30) |")
L.append('')
L.append(f"Puck CG {M['puck_cg_local_mm'][2]:.1f} mm above the base. Getting under 30 g, calculated: PETG walls 1.4 → 1.0 mm (about −3.5 g) "
         "and a 1.0 mm PCB instead of 1.6 mm (about −2 g) give about 29 g.")
L.append('')
L.append('Catalogue masses used (approximate, class values, check against the purchased parts): 2809 motor 62 g, HQ 7x4x3 prop 8 g, '
         '4-in-1 6S ESC 28 g, 6S 3300 mAh pack 490 g (baseline), Pixhawk 6C Mini 39.2 g, power module + buck 30 g, '
         'ESP32-C3 + RFM95W + receiver 27 g, 868 MHz antenna 8 g, Raspberry Pi 5 46 g, active cooler 22 g, STL-19P LiDAR 47 g, '
         'IMX327 module 15 g, MLX90640 5 g, IR LED + optic 3 g each, gas cells 36 g (3), sampling pump 25 g, MG90S 13.4 g, '
         '6800-2RS bearing 5.5 g, 1S 400 mAh LiPo 8.5 g. Allowances: fasteners 25 g, sensor harness/mounts 10 g, wiring 80 g (baseline).')
open(os.path.join(CAD, 'mass-properties.md'), 'w').write('\n'.join(L) + '\n')
print('\n'.join(L[:30]))
