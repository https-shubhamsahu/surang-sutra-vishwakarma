def vp(lib, ref, value, x, y, top, bot, fp, mpn='', dnp=False, r=0):
    i = s.place(lib, ref, value, x, y, r=r, fp=fp, fields={'MPN': mpn} if mpn else None, dnp=dnp,
                refpos=(x + 2.54, y - 1.27, 0, 'left') if r else None, valpos=(x + 2.54, y + 1.27, 0, 'left') if r else None)
    a, b = sorted(i.pins.values(), key=lambda p: p['y'])[:2]   # upper pin, lower pin
    s.net(i, a['number'], top)
    s.net(i, b['number'], bot)
    return i


def R(ref, value, x, y, top, bot, mpn=''):
    return vp('Device:R', ref, value, x, y, top, bot, R0603, mpn or f'0603 {value} 1%')


def C(ref, value, x, y, top, bot, fp=C0603, mpn=''):
    return vp('Device:C', ref, value, x, y, top, bot, fp, mpn or f'X7R 16V 0603 {value}')


def TP(ref, value, x, y, net, up=True, fp='TestPoint:TestPoint_Pad_D1.5mm'):
    r = 180 if up else 0
    i = s.place('Connector:TestPoint', ref, value, x, y, r=r, fp=fp, in_bom=False,
                refpos=(x + 2.54, y + (3.3 if up else -4.3), 0, 'left'), valpos=(x + 2.54, y + (5.3 if up else -2.3), 0, 'left'))
    s.net(i, '1', net)
    return i


