def vp(lib, ref, value, x, y, top, bot, fp='', mpn='', r=0, dnp=False):
    i = s.place(lib, ref, value, x, y, r=r, fp=fp, fields={'MPN': mpn} if mpn else None, dnp=dnp,
                refpos=(x + 2.54, y - 1.27, 0, 'left'), valpos=(x + 2.54, y + 1.27, 0, 'left'))
    a, b = sorted(i.pins.values(), key=lambda p: p['y'])[:2]
    s.net(i, a['number'], top)
    s.net(i, b['number'], bot)
    return i


def box(sym, ref, value, x, y, conns, mpn='', fp='', valpos=None):
    i = s.place(f'{L}:{sym}', ref, value, x, y, fields={'MPN': mpn} if mpn else None, fp=fp, valpos=valpos)
    for k, n in conns.items():
        if n is None:
            s.nc(i, k)
        else:
            s.net(i, k, n)
    return i


